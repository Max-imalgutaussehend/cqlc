//! Rust code generation from the typed IR, targeting the ScyllaDB driver.

use crate::emit::Emitter;
use crate::naming::{const_ident, field_ident, to_pascal_case, to_snake_case};
use cqlc_core::ast::QueryKind;
use cqlc_core::diagnostic::{Diagnostic, DiagnosticCode};
use cqlc_core::ir::{Ir, Param, ParamSource, Query};
use cqlc_core::schema::Udt;
use cqlc_core::span::Span;
use cqlc_core::types::CqlType;
use std::collections::{BTreeSet, HashMap};

/// Which Rust types represent `timestamp`, `date` and `time`.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
#[non_exhaustive]
pub enum TimeLibrary {
    /// `scylla::value::{CqlTimestamp, CqlDate, CqlTime}`
    #[default]
    Native,
    /// `chrono` types; needs scylla's `chrono-04` feature.
    Chrono,
}

/// Code generation options. Start from [`Options::new`] and adjust.
#[derive(Clone, Debug)]
#[non_exhaustive]
pub struct Options {
    /// Types for `timestamp`, `date` and `time`.
    pub time_library: TimeLibrary,
    /// Also generate `stream_*` functions for `:many` queries. They return
    /// a `futures::stream::BoxStream` and need the `futures` crate.
    pub streams: bool,
}

impl Options {
    /// The defaults: native driver time types, streams enabled.
    pub fn new() -> Self {
        Options {
            time_library: TimeLibrary::Native,
            streams: true,
        }
    }

    /// Sets the time library.
    pub fn time_library(mut self, time_library: TimeLibrary) -> Self {
        self.time_library = time_library;
        self
    }

    /// Enables or disables `stream_*` functions.
    pub fn streams(mut self, streams: bool) -> Self {
        self.streams = streams;
        self
    }
}

impl Default for Options {
    fn default() -> Self {
        Options::new()
    }
}

/// Version of the layout of the generated code. It changes only when the
/// shape of the generated API changes, not with every cqlc release, so
/// patch releases do not make `generate --check` fail.
pub const OUTPUT_FORMAT: u32 = 1;

const RESERVED_FNS: [&str; 2] = ["new", "session"];

/// Generates one Rust module for all queries. Output is deterministic: the
/// same IR and options always produce the same text.
///
/// Fails with diagnostics when a type has no Rust mapping or generated names
/// would clash.
pub fn generate_rust(ir: &Ir, opts: &Options) -> Result<String, Vec<Diagnostic>> {
    let mut errors = Vec::new();
    for q in &ir.queries {
        if !matches!(
            q.kind,
            QueryKind::One | QueryKind::Many | QueryKind::Exec | QueryKind::Lwt
        ) {
            errors.push(Diagnostic::error(
                DiagnosticCode::Unsupported,
                q.span,
                format!(
                    "query kind of `{}` is not supported by this version of cqlc",
                    q.name
                ),
            ));
        }
    }
    if !errors.is_empty() {
        return Err(errors);
    }
    check_name_clashes(ir, opts, &mut errors);
    if !errors.is_empty() {
        return Err(errors);
    }
    let mut e = Emitter::default();
    header(&mut e);

    let used = used_udts(ir);
    for udt in ir.udts.iter().filter(|u| used.contains(&u.name)) {
        match udt_struct(udt, ir, opts) {
            Ok(code) => e.line(code),
            Err(mut d) => errors.append(&mut d),
        }
    }
    let mut generated = Vec::new();
    for q in &ir.queries {
        match query(q, ir, opts) {
            Ok(g) => {
                e.line(&g.code);
                generated.push(g);
            }
            Err(mut d) => errors.append(&mut d),
        }
    }
    if !errors.is_empty() {
        return Err(errors);
    }
    e.line(queries_struct(&generated));
    Ok(e.finish())
}

fn header(e: &mut Emitter) {
    e.line(format!(
        "// @generated by cqlc (output format {OUTPUT_FORMAT}). DO NOT EDIT."
    ));
    e.line("//");
    e.line("// Regenerate with `cqlc generate`; verify in CI with `cqlc generate --check`.");
    e.line("// Declare this module with `#[rustfmt::skip]` so rustfmt leaves it alone.");
    e.blank();
    e.line("#![allow(dead_code, clippy::all)]");
    e.blank();
    e.line("/// The stage of a query that failed.");
    e.line("#[derive(Debug, Clone, Copy, PartialEq, Eq)]");
    e.line("#[non_exhaustive]");
    e.open("pub enum CqlcErrorKind");
    e.line("/// Preparing the statement failed.");
    e.line("Prepare,");
    e.line("/// Executing the statement failed.");
    e.line("Execute,");
    e.line("/// The response did not contain a usable result set.");
    e.line("Rows,");
    e.line("/// A row did not match the generated row type.");
    e.line("Deserialize,");
    e.close();
    e.blank();
    e.line("/// Error returned by every generated query function.");
    e.line("#[derive(Debug)]");
    e.open("pub struct CqlcError");
    e.line("/// Name of the query, as written in its `-- name:` annotation.");
    e.line("pub query: &'static str,");
    e.line("pub kind: CqlcErrorKind,");
    e.line("source: ::std::boxed::Box<dyn ::std::error::Error + Send + Sync + 'static>,");
    e.close();
    e.blank();
    e.open("impl CqlcError");
    e.open("fn new(query: &'static str, kind: CqlcErrorKind, source: impl ::std::error::Error + Send + Sync + 'static) -> Self");
    e.line("CqlcError { query, kind, source: ::std::boxed::Box::new(source) }");
    e.close();
    e.close();
    e.blank();
    e.open("impl ::std::fmt::Display for CqlcError");
    e.open("fn fmt(&self, f: &mut ::std::fmt::Formatter<'_>) -> ::std::fmt::Result");
    e.line("write!(f, \"query `{}` failed ({:?}): {}\", self.query, self.kind, self.source)");
    e.close();
    e.close();
    e.blank();
    e.open("impl ::std::error::Error for CqlcError");
    e.open("fn source(&self) -> Option<&(dyn ::std::error::Error + 'static)>");
    e.line("Some(&*self.source)");
    e.close();
    e.close();
    e.blank();
}

// ----- UDTs ------------------------------------------------------------------

fn collect_udts(ty: &CqlType, ir: &Ir, out: &mut BTreeSet<String>) {
    match ty {
        CqlType::Udt(name) => {
            if out.insert(name.clone())
                && let Some(u) = ir.udts.iter().find(|u| &u.name == name)
            {
                for (_, f) in &u.fields {
                    collect_udts(f, ir, out);
                }
            }
        }
        CqlType::List(t) | CqlType::Set(t) | CqlType::Frozen(t) | CqlType::Vector(t, _) => {
            collect_udts(t, ir, out)
        }
        CqlType::Map(k, v) => {
            collect_udts(k, ir, out);
            collect_udts(v, ir, out);
        }
        CqlType::Tuple(ts) => ts.iter().for_each(|t| collect_udts(t, ir, out)),
        _ => {}
    }
}

/// User-defined types reachable from any query parameter or result column.
fn used_udts(ir: &Ir) -> BTreeSet<String> {
    let mut out = BTreeSet::new();
    for q in &ir.queries {
        for p in &q.params {
            collect_udts(&p.cql_type, ir, &mut out);
        }
        for c in &q.columns {
            collect_udts(&c.cql_type, ir, &mut out);
        }
    }
    out
}

fn udt_struct(udt: &Udt, ir: &Ir, opts: &Options) -> Result<String, Vec<Diagnostic>> {
    let mut errors = Vec::new();
    let mut e = Emitter::default();
    let name = to_pascal_case(&udt.name);
    let mut derives = "Debug, Clone, PartialEq".to_string();
    if is_ord(&CqlType::Udt(udt.name.clone()), &ir.udts) {
        derives.push_str(", Eq, PartialOrd, Ord");
    }
    e.line(format!(
        "/// User-defined type `{}`. Every field may be absent.",
        doc(&udt.name)
    ));
    e.line(format!(
        "#[derive({derives}, ::scylla::SerializeValue, ::scylla::DeserializeValue)]"
    ));
    e.open(format!("pub struct {name}"));
    let mut seen = Vec::new();
    for (field, ty) in &udt.fields {
        let ident = field_ident(field);
        if seen.contains(&ident) {
            errors.push(Diagnostic::error(
                DiagnosticCode::Duplicate,
                udt.span,
                format!(
                    "field names of type `{}` clash after conversion to Rust: `{ident}`",
                    udt.name
                ),
            ));
        }
        seen.push(ident.clone());
        match rust_type(ty, opts, false, &ir.udts) {
            Ok(t) => {
                if &ident != field {
                    e.line(format!("#[scylla(rename = {field:?})]"));
                }
                e.line(format!("pub {ident}: ::std::option::Option<{t}>,"));
            }
            Err(msg) => errors.push(Diagnostic::error(
                DiagnosticCode::UnsupportedType,
                udt.span,
                msg,
            )),
        }
    }
    e.close();
    e.blank();
    if errors.is_empty() {
        Ok(e.finish().trim_end_matches('\n').to_string() + "\n")
    } else {
        Err(errors)
    }
}

// ----- queries ---------------------------------------------------------------

struct Generated {
    code: String,
    /// Query name as written in the annotation.
    name: String,
    snake: String,
    cql_const: String,
    arg_decl: String,
    arg_pass: String,
    ret: String,
    stream_ret: Option<String>,
}

fn query(q: &Query, ir: &Ir, opts: &Options) -> Result<Generated, Vec<Diagnostic>> {
    let mut errors = Vec::new();
    let mut ty = |t: &CqlType| match rust_type(t, opts, false, &ir.udts) {
        Ok(s) => s,
        Err(msg) => {
            errors.push(Diagnostic::error(
                DiagnosticCode::UnsupportedType,
                q.span,
                msg,
            ));
            String::new()
        }
    };

    let snake = to_snake_case(&q.name);
    let pascal = to_pascal_case(&q.name);
    let cql_const = format!("{}_CQL", const_ident(&snake));
    let row = format!("{pascal}Row");
    let params_ty = format!("{pascal}Params");
    let outcome = format!("{pascal}Outcome");

    let params: Vec<(String, String, &Param)> = q
        .params
        .iter()
        .map(|p| {
            let t = ty(&p.cql_type);
            let t = if p.nullable {
                format!("::std::option::Option<{t}>")
            } else {
                t
            };
            (field_ident(&p.name), t, p)
        })
        .collect();
    let cols: Vec<(String, String, &str)> = q
        .columns
        .iter()
        .map(|c| {
            let t = ty(&c.cql_type);
            let t = if c.nullable {
                format!("::std::option::Option<{t}>")
            } else {
                t
            };
            let mut ident = field_ident(&c.name);
            if q.kind == QueryKind::Lwt && ident == "applied" {
                ident.push('_');
            }
            (ident, t, c.name.as_str())
        })
        .collect();
    let full_cols: Vec<(String, String, &str)> = if full_extra_column(q).is_some() {
        q.row_columns
            .iter()
            .map(|c| {
                let t = ty(&c.cql_type);
                let mut ident = field_ident(&c.name);
                if ident == "applied" {
                    ident.push('_');
                }
                (
                    ident,
                    format!("::std::option::Option<{t}>"),
                    c.name.as_str(),
                )
            })
            .collect()
    } else {
        Vec::new()
    };
    for (what, names) in [
        (
            "parameter",
            params.iter().map(|p| p.0.as_str()).collect::<Vec<_>>(),
        ),
        ("result column", cols.iter().map(|c| c.0.as_str()).collect()),
    ] {
        if let Some(dup) = first_duplicate(&names) {
            errors.push(Diagnostic::error(
                DiagnosticCode::Duplicate,
                q.span,
                format!("{what} names clash after conversion to Rust: `{dup}`"),
            ));
        }
    }
    if !errors.is_empty() {
        return Err(errors);
    }

    let mut e = Emitter::default();
    let kind_name = match q.kind {
        QueryKind::One => ":one",
        QueryKind::Many => ":many",
        QueryKind::Exec => ":exec",
        _ => ":lwt",
    };

    e.line(format!("/// CQL of [`{snake}`] (`{}`).", doc(&q.name)));
    e.line(format!("pub const {cql_const}: &str = {:?};", q.cql));
    e.blank();

    // Row / outcome types.
    match q.kind {
        QueryKind::One | QueryKind::Many => {
            e.line(format!("/// One result row of [`{snake}`]."));
            e.line("#[derive(Debug, Clone, PartialEq, ::scylla::DeserializeRow)]");
            e.open(format!("pub struct {row}"));
            for (field, t, cql_name) in &cols {
                if field != cql_name {
                    e.line(format!("#[scylla(rename = {cql_name:?})]"));
                }
                e.line(format!("pub {field}: {t},"));
            }
            e.close();
            e.blank();
        }
        QueryKind::Lwt => {
            e.line(format!("/// Result of the conditional write [`{snake}`]."));
            e.line("#[derive(Debug, Clone, PartialEq)]");
            e.open(format!("pub struct {outcome}"));
            e.line("/// Whether the write was applied.");
            e.line("pub applied: bool,");
            for (field, t, _) in &cols {
                e.line("/// Current value, reported by the database when `applied` is false.");
                e.line(format!("pub {field}: {t},"));
            }
            e.close();
            e.blank();
            e.line("#[derive(::scylla::DeserializeRow)]");
            e.open(format!("struct {pascal}Applied"));
            e.line("#[scylla(rename = \"[applied]\")]");
            e.line("applied: bool,");
            e.close();
            e.blank();
            if !cols.is_empty() {
                e.line("#[derive(::scylla::DeserializeRow)]");
                e.open(format!("struct {pascal}Current"));
                e.line("#[scylla(rename = \"[applied]\")]");
                e.line("applied: bool,");
                for (field, t, cql_name) in &cols {
                    if field != cql_name {
                        e.line(format!("#[scylla(rename = {cql_name:?})]"));
                    }
                    e.line(format!("{field}: {t},"));
                }
                e.close();
                e.blank();
            }
            if full_extra_column(q).is_some() {
                e.line("#[derive(::scylla::DeserializeRow)]");
                e.open(format!("struct {pascal}Full"));
                e.line("#[scylla(rename = \"[applied]\")]");
                e.line("applied: bool,");
                for (field, t, cql_name) in &full_cols {
                    if field != cql_name {
                        e.line(format!("#[scylla(rename = {cql_name:?})]"));
                    }
                    e.line(format!("{field}: {t},"));
                }
                e.close();
                e.blank();
            }
        }
        _ => {}
    }

    let use_struct = params.len() > 1;
    if use_struct {
        e.line(format!(
            "/// Bind values of [`{snake}`], in the order of the bind markers."
        ));
        e.line("#[derive(Debug, Clone, PartialEq)]");
        e.open(format!("pub struct {params_ty}"));
        for (field, t, p) in &params {
            e.line(format!("/// {}", doc(&param_doc(p))));
            e.line(format!("pub {field}: {t},"));
        }
        e.close();
        e.blank();
    }

    let ret = match q.kind {
        QueryKind::One => format!("::std::result::Result<::std::option::Option<{row}>, CqlcError>"),
        QueryKind::Many => format!("::std::result::Result<::std::vec::Vec<{row}>, CqlcError>"),
        QueryKind::Exec => "::std::result::Result<(), CqlcError>".to_string(),
        _ => format!("::std::result::Result<{outcome}, CqlcError>"),
    };
    let stream_ret = (q.kind == QueryKind::Many && opts.streams).then(|| {
        format!("::std::result::Result<::futures::stream::BoxStream<'static, ::std::result::Result<{row}, CqlcError>>, CqlcError>")
    });
    let single_name = |field: &str| match field {
        "session" | "prepared" | "result" | "rows" | "pager" | "stream" => format!("{field}_"),
        _ => field.to_string(),
    };
    let (arg_decl, arg_pass) = match params.as_slice() {
        [] => (String::new(), String::new()),
        [(field, t, _)] => {
            let f = single_name(field);
            (format!(", {f}: {t}"), format!(", {f}"))
        }
        _ => (format!(", params: {params_ty}"), ", params".to_string()),
    };
    let binding = match params.as_slice() {
        [] => "()".to_string(),
        [(field, _, _)] => format!("(&{},)", single_name(field)),
        _ => format!(
            "({},)",
            params
                .iter()
                .map(|(f, _, _)| format!("&params.{f}"))
                .collect::<Vec<_>>()
                .join(", ")
        ),
    };
    let name = format!("{:?}", q.name);
    let err = |kind: &str| format!("|e| CqlcError::new({name}, CqlcErrorKind::{kind}, e)");
    let session_ty = "&::scylla::client::session::Session";
    let prepared_ty = "&::scylla::statement::prepared::PreparedStatement";

    // Internal function running an already prepared statement.
    e.open(format!(
        "async fn {snake}_with(session: {session_ty}, prepared: {prepared_ty}{arg_decl}) -> {ret}"
    ));
    let exec = format!("session.execute_unpaged(prepared, {binding}).await");
    match q.kind {
        QueryKind::Exec => {
            e.line(format!("{exec}.map_err({})?;", err("Execute")));
            e.line("Ok(())");
        }
        _ => {
            e.line(format!("let result = {exec}.map_err({})?;", err("Execute")));
            e.line(format!(
                "let rows = result.into_rows_result().map_err({})?;",
                err("Rows")
            ));
            match q.kind {
                QueryKind::One => {
                    e.line(format!(
                        "rows.maybe_first_row::<{row}>().map_err({})",
                        err("Deserialize")
                    ));
                }
                QueryKind::Many => {
                    e.line(format!("rows.rows::<{row}>().map_err({})?", err("Rows")));
                    e.line("    .collect::<::std::result::Result<::std::vec::Vec<_>, _>>()");
                    e.line(format!("    .map_err({})", err("Deserialize")));
                }
                QueryKind::Lwt => {
                    // The database reports back only `[applied]` for a successful write.
                    // For a failed one, Cassandra returns the tested columns and ScyllaDB the
                    // whole row, so recognize which shape came back.
                    let extra = full_extra_column(q);
                    let moves = |src: &str| -> String {
                        cols.iter()
                            .map(|(f, _, _)| format!(", {f}: {src}.{f}"))
                            .collect()
                    };
                    let nones: String = cols
                        .iter()
                        .map(|(f, _, _)| format!(", {f}: None"))
                        .collect();
                    e.line("let specs = rows.column_specs();");
                    e.open("if specs.len() <= 1");
                    e.line(format!(
                        "let applied = rows.first_row::<{pascal}Applied>().map_err({})?;",
                        err("Deserialize")
                    ));
                    e.line(format!(
                        "Ok({outcome} {{ applied: applied.applied{nones} }})"
                    ));
                    if let Some(extra) = &extra {
                        e.reopen(format!(
                            "}} else if specs.iter().any(|c| c.name() == {extra:?}) {{"
                        ));
                        e.line(format!(
                            "let full = rows.first_row::<{pascal}Full>().map_err({})?;",
                            err("Deserialize")
                        ));
                        e.line(format!(
                            "Ok({outcome} {{ applied: full.applied{} }})",
                            moves("full")
                        ));
                    }
                    if cols.is_empty() {
                        e.reopen("} else {");
                        e.line(format!(
                            "let applied = rows.first_row::<{pascal}Applied>().map_err({})?;",
                            err("Deserialize")
                        ));
                        e.line(format!("Ok({outcome} {{ applied: applied.applied }})"));
                    } else {
                        e.reopen("} else {");
                        e.line(format!(
                            "let current = rows.first_row::<{pascal}Current>().map_err({})?;",
                            err("Deserialize")
                        ));
                        e.line(format!(
                            "Ok({outcome} {{ applied: current.applied{} }})",
                            moves("current")
                        ));
                    }
                    e.close();
                }
                _ => unreachable!(),
            }
        }
    }
    e.close();
    e.blank();

    // Public function: prepare, then run.
    e.line(format!(
        "/// Runs query `{}` (`{kind_name}`).",
        doc(&q.name)
    ));
    e.line("///");
    e.line("/// ```text");
    e.line(format!("/// {}", doc(&q.cql)));
    e.line("/// ```");
    match q.kind {
        QueryKind::One => {
            e.line("///");
            e.line(
                "/// Returns `None` if no row matched. The query is expected to match at most one",
            );
            e.line("/// row; if it matches several, the first one is returned.");
        }
        QueryKind::Many => {
            e.line("///");
            e.line(
                "/// Loads the whole result set into memory (unpaged); see the `stream_` variant",
            );
            e.line("/// for large results.");
        }
        QueryKind::Lwt => {
            e.line("///");
            e.line("/// A conditional write that is not applied is not an error: check `applied`.");
        }
        _ => {}
    }
    e.line("///");
    e.line("/// Prepares the statement on every call; use [`Queries`] to prepare once.");
    e.open(format!(
        "pub async fn {snake}(session: {session_ty}{arg_decl}) -> {ret}"
    ));
    e.line(format!(
        "let prepared = session.prepare({cql_const}).await.map_err({})?;",
        err("Prepare")
    ));
    e.line(format!("{snake}_with(session, &prepared{arg_pass}).await"));
    e.close();
    e.blank();

    if let Some(stream_ret) = &stream_ret {
        e.open(format!(
            "async fn stream_{snake}_with(session: {session_ty}, prepared: {prepared_ty}{arg_decl}) -> {stream_ret}"
        ));
        e.line(format!(
            "let pager = session.execute_iter(prepared.clone(), {binding}).await.map_err({})?;",
            err("Execute")
        ));
        e.line(format!(
            "let stream = pager.rows_stream::<{row}>().map_err({})?;",
            err("Rows")
        ));
        e.line(format!(
            "Ok(::futures::StreamExt::boxed(::futures::StreamExt::map(stream, |r| r.map_err({}))))",
            err("Deserialize")
        ));
        e.close();
        e.blank();
        e.line(format!(
            "/// Streams the rows of query `{}` page by page.",
            q.name
        ));
        e.line("///");
        e.line("/// Rows are deserialized lazily; the full result is never held in memory.");
        e.line("/// Prepares the statement on every call; use [`Queries`] to prepare once.");
        e.open(format!(
            "pub async fn stream_{snake}(session: {session_ty}{arg_decl}) -> {stream_ret}"
        ));
        e.line(format!(
            "let prepared = session.prepare({cql_const}).await.map_err({})?;",
            err("Prepare")
        ));
        e.line(format!(
            "stream_{snake}_with(session, &prepared{arg_pass}).await"
        ));
        e.close();
        e.blank();
    }

    if !errors.is_empty() {
        return Err(errors);
    }
    Ok(Generated {
        code: e.finish().trim_end_matches('\n').to_string() + "\n",
        name: q.name.clone(),
        snake,
        cql_const,
        arg_decl,
        arg_pass,
        ret,
        stream_ret,
    })
}

/// A table column that a conditional write reports only when the server
/// returns the whole row (ScyllaDB); `None` if the tested columns already are
/// the whole row.
fn full_extra_column(q: &Query) -> Option<String> {
    if q.kind != QueryKind::Lwt {
        return None;
    }
    q.row_columns
        .iter()
        .find(|c| !q.columns.iter().any(|x| x.name == c.name))
        .map(|c| c.name.clone())
}

/// A struct holding every statement prepared once.
fn queries_struct(items: &[Generated]) -> String {
    let mut e = Emitter::default();
    let prepared_ty = "::scylla::statement::prepared::PreparedStatement";
    e.line("/// All queries, prepared once. Cheap to share behind an `Arc`.");
    e.line("///");
    e.line("/// Prefer this over the free functions when queries run repeatedly: each free");
    e.line("/// function prepares its statement on every call.");
    e.line("#[derive(Debug)]");
    e.open("pub struct Queries");
    e.line("session: ::std::sync::Arc<::scylla::client::session::Session>,");
    for g in items {
        e.line(format!("{}: {prepared_ty},", g.snake));
    }
    e.close();
    e.blank();
    e.open("impl Queries");
    e.line("/// Prepares every statement on `session`.");
    e.open("pub async fn new(session: ::std::sync::Arc<::scylla::client::session::Session>) -> ::std::result::Result<Self, CqlcError>");
    for g in items {
        e.line(format!(
            "let {} = session.prepare({}).await.map_err(|e| CqlcError::new({:?}, CqlcErrorKind::Prepare, e))?;",
            g.snake,
            g.cql_const,
            g.name
        ));
    }
    let fields: String = items.iter().map(|g| format!(", {}", g.snake)).collect();
    e.line(format!("Ok(Queries {{ session{fields} }})"));
    e.close();
    e.blank();
    e.line("/// The session the statements were prepared on.");
    e.open("pub fn session(&self) -> &::scylla::client::session::Session");
    e.line("&self.session");
    e.close();
    for g in items {
        e.blank();
        e.open(format!(
            "pub async fn {}(&self{}) -> {}",
            g.snake, g.arg_decl, g.ret
        ));
        e.line(format!(
            "{}_with(&self.session, &self.{}{}).await",
            g.snake, g.snake, g.arg_pass
        ));
        e.close();
        if let Some(sr) = &g.stream_ret {
            e.blank();
            e.open(format!(
                "pub async fn stream_{}(&self{}) -> {sr}",
                g.snake, g.arg_decl
            ));
            e.line(format!(
                "stream_{}_with(&self.session, &self.{}{}).await",
                g.snake, g.snake, g.arg_pass
            ));
            e.close();
        }
    }
    e.close();
    e.finish()
}

/// Makes arbitrary text safe inside a `///` line: no line breaks that would
/// turn the rest into code, and no control or bidirectional-formatting
/// characters that could hide code from a reader.
fn doc(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    for c in text.chars() {
        match c {
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push(' '),
            c if c.is_control()
                || matches!(
                    c,
                    '\u{200b}'..='\u{200f}'
                        | '\u{2028}'..='\u{202e}'
                        | '\u{2060}'..='\u{2069}'
                        | '\u{feff}'
                ) =>
            {
                out.push_str(&format!("\\u{{{:04x}}}", c as u32));
            }
            c => out.push(c),
        }
    }
    out
}

fn param_doc(p: &Param) -> String {
    let what = match &p.source {
        ParamSource::Restriction { column, op } => format!("`{column}` ({})", op.suffix()),
        ParamSource::Condition { column, op } => format!("`IF {column}` ({})", op.suffix()),
        ParamSource::Assignment { column } => format!("`{column}`"),
        ParamSource::ElementKey { column } => format!("map key or list index of `{column}`"),
        ParamSource::ElementValue { column } => format!("element value of `{column}`"),
        ParamSource::Json => "the JSON document".to_string(),
        ParamSource::Expression => "value used in an expression".to_string(),
        ParamSource::Limit => "`LIMIT`".to_string(),
        ParamSource::PerPartitionLimit => "`PER PARTITION LIMIT`".to_string(),
        ParamSource::Ttl => "`USING TTL` (seconds)".to_string(),
        ParamSource::Timestamp => "`USING TIMESTAMP` (microseconds)".to_string(),
        _ => "bind value".to_string(),
    };
    if p.nullable {
        format!("{what}. `None` binds NULL (a delete marker), it does not leave the value unset.")
    } else {
        what
    }
}

fn first_duplicate<'a>(names: &[&'a str]) -> Option<&'a str> {
    let mut seen = std::collections::HashSet::new();
    names.iter().copied().find(|n| !seen.insert(*n))
}

/// Rust names must be unique across everything generated into the module.
fn check_name_clashes(ir: &Ir, opts: &Options, errors: &mut Vec<Diagnostic>) {
    let used = used_udts(ir);
    let mut types: HashMap<String, String> = HashMap::new();
    let mut fns: HashMap<String, String> = HashMap::new();
    let report =
        |errors: &mut Vec<Diagnostic>, span: Span, what: &str, a: &str, b: &str, name: &str| {
            errors.push(
                Diagnostic::error(
                    DiagnosticCode::Duplicate,
                    span,
                    format!("{what} `{a}` and `{b}` both map to the Rust name `{name}`"),
                )
                .with_help("rename one of them"),
            );
        };
    for t in ["CqlcError", "CqlcErrorKind", "Queries"] {
        types.insert(t.into(), format!("generated `{t}`"));
    }
    for u in ir.udts.iter().filter(|u| used.contains(&u.name)) {
        let n = to_pascal_case(&u.name);
        if let Some(prev) = types.insert(n.clone(), format!("type `{}`", u.name)) {
            report(
                errors,
                u.span,
                "types",
                &prev,
                &format!("type `{}`", u.name),
                &n,
            );
        }
    }
    for q in &ir.queries {
        let snake = to_snake_case(&q.name);
        let pascal = to_pascal_case(&q.name);
        let mut fn_names = vec![snake.clone(), format!("{snake}_with")];
        if q.kind == QueryKind::Many && opts.streams {
            fn_names.push(format!("stream_{snake}"));
            fn_names.push(format!("stream_{snake}_with"));
        }
        if RESERVED_FNS.contains(&snake.as_str()) {
            errors.push(Diagnostic::error(
                DiagnosticCode::Duplicate,
                q.span,
                format!(
                    "query name `{}` maps to the reserved Rust name `{snake}`",
                    q.name
                ),
            ));
        }
        for f in fn_names {
            if let Some(prev) = fns.insert(f.clone(), format!("query `{}`", q.name)) {
                report(
                    errors,
                    q.span,
                    "functions of",
                    &prev,
                    &format!("query `{}`", q.name),
                    &f,
                );
            }
        }
        let mut type_names = Vec::new();
        match q.kind {
            QueryKind::One | QueryKind::Many => type_names.push(format!("{pascal}Row")),
            QueryKind::Lwt => type_names.extend([
                format!("{pascal}Outcome"),
                format!("{pascal}Applied"),
                format!("{pascal}Current"),
                format!("{pascal}Full"),
            ]),
            _ => {}
        }
        if q.params.len() > 1 {
            type_names.push(format!("{pascal}Params"));
        }
        for t in type_names {
            if let Some(prev) = types.insert(t.clone(), format!("query `{}`", q.name)) {
                report(
                    errors,
                    q.span,
                    "types of",
                    &prev,
                    &format!("query `{}`", q.name),
                    &t,
                );
            }
        }
    }
}

/// Maps a CQL type to a Rust type path. `ord` demands a type with a total
/// order (set elements and map keys are stored in `BTreeSet`/`BTreeMap`).
fn rust_type(ty: &CqlType, opts: &Options, ord: bool, udts: &[Udt]) -> Result<String, String> {
    use CqlType::*;
    let chrono = opts.time_library == TimeLibrary::Chrono;
    if ord && !is_ord(ty, udts) {
        return Err(format!(
            "`{ty}` cannot be a set element or map key: it has no total order in Rust"
        ));
    }
    Ok(match ty {
        Ascii | Text => "::std::string::String".into(),
        BigInt => "i64".into(),
        Blob => "::std::vec::Vec<u8>".into(),
        Boolean => "bool".into(),
        Counter => "::scylla::value::Counter".into(),
        Date if chrono => "::chrono::NaiveDate".into(),
        Date => "::scylla::value::CqlDate".into(),
        Decimal => "::scylla::value::CqlDecimal".into(),
        Double => "f64".into(),
        Duration => "::scylla::value::CqlDuration".into(),
        Float => "f32".into(),
        Inet => "::std::net::IpAddr".into(),
        Int => "i32".into(),
        SmallInt => "i16".into(),
        Time if chrono => "::chrono::NaiveTime".into(),
        Time => "::scylla::value::CqlTime".into(),
        Timestamp if chrono => "::chrono::DateTime<::chrono::Utc>".into(),
        Timestamp => "::scylla::value::CqlTimestamp".into(),
        TimeUuid => "::scylla::value::CqlTimeuuid".into(),
        TinyInt => "i8".into(),
        Uuid => "::uuid::Uuid".into(),
        VarInt => "::scylla::value::CqlVarint".into(),
        List(t) | Vector(t, _) => {
            format!("::std::vec::Vec<{}>", rust_type(t, opts, false, udts)?)
        }
        Set(t) => format!(
            "::std::collections::BTreeSet<{}>",
            rust_type(t, opts, true, udts)?
        ),
        Map(k, v) => format!(
            "::std::collections::BTreeMap<{}, {}>",
            rust_type(k, opts, true, udts)?,
            rust_type(v, opts, false, udts)?
        ),
        Tuple(ts) => {
            let parts: Result<Vec<_>, _> =
                ts.iter().map(|t| rust_type(t, opts, false, udts)).collect();
            format!("({},)", parts?.join(", "))
        }
        Frozen(t) => rust_type(t, opts, ord, udts)?,
        Udt(name) => {
            if !udts.iter().any(|u| &u.name == name) {
                return Err(format!("unknown user-defined type `{name}`"));
            }
            to_pascal_case(name)
        }
        _ => {
            return Err(format!(
                "type `{ty}` is not supported by this version of cqlc"
            ));
        }
    })
}

fn is_ord(ty: &CqlType, udts: &[Udt]) -> bool {
    is_ord_inner(ty, udts, &mut Vec::new())
}

fn is_ord_inner(ty: &CqlType, udts: &[Udt], seen: &mut Vec<String>) -> bool {
    use CqlType::*;
    match ty {
        Ascii | Text | Boolean | TinyInt | SmallInt | Int | BigInt | Uuid | TimeUuid
        | Timestamp | Date | Time | Inet | Blob => true,
        List(t) | Set(t) | Frozen(t) | Vector(t, _) => is_ord_inner(t, udts, seen),
        Map(k, v) => is_ord_inner(k, udts, seen) && is_ord_inner(v, udts, seen),
        Tuple(ts) => ts.iter().all(|t| is_ord_inner(t, udts, seen)),
        Udt(name) => {
            if seen.contains(name) {
                return false;
            }
            seen.push(name.clone());
            let ok = udts
                .iter()
                .find(|u| &u.name == name)
                .is_some_and(|u| u.fields.iter().all(|(_, t)| is_ord_inner(t, udts, seen)));
            seen.pop();
            ok
        }
        _ => false,
    }
}
