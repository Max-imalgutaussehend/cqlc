//! Rust code generation from the typed IR, targeting the ScyllaDB driver.

use crate::emit::Emitter;
use crate::naming::{const_ident, field_ident, to_pascal_case, to_snake_case};
use cqlc_core::ast::QueryKind;
use cqlc_core::diagnostic::{Diagnostic, DiagnosticCode};
use cqlc_core::ir::{Ir, Param, Query};
use cqlc_core::types::CqlType;
use std::collections::HashMap;

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum TimeLibrary {
    /// `scylla::value::{CqlTimestamp, CqlDate, CqlTime}`
    #[default]
    Native,
    /// `chrono` types; needs scylla's `chrono-04` feature.
    Chrono,
}

#[derive(Clone, Debug, Default)]
pub struct Options {
    pub time_library: TimeLibrary,
}

const CRATE_VERSION: &str = env!("CARGO_PKG_VERSION");

/// Generates one Rust module for all queries. Output is deterministic.
pub fn generate_rust(ir: &Ir, opts: &Options) -> Result<String, Vec<Diagnostic>> {
    let mut errors = Vec::new();
    check_name_clashes(ir, &mut errors);
    let mut e = Emitter::default();
    header(&mut e);
    for q in &ir.queries {
        match query(q, opts) {
            Ok(code) => e.line(code),
            Err(mut d) => errors.append(&mut d),
        }
    }
    if errors.is_empty() {
        Ok(e.finish())
    } else {
        Err(errors)
    }
}

fn header(e: &mut Emitter) {
    e.line(format!(
        "// @generated by cqlc {CRATE_VERSION}. DO NOT EDIT."
    ));
    e.line("//");
    e.line("// Regenerate with `cqlc generate`; verify in CI with `cqlc generate --check`.");
    e.line("// Declare this module with `#[rustfmt::skip]` so rustfmt leaves it alone.");
    e.blank();
    e.line("#![allow(clippy::all)]");
    e.blank();
    e.line("/// The stage of a query that failed.");
    e.line("#[derive(Debug, Clone, Copy, PartialEq, Eq)]");
    e.line("#[non_exhaustive]");
    e.open("pub enum CqlcErrorKind");
    e.line("/// Preparing the statement failed.");
    e.line("Prepare,");
    e.line("/// Executing the statement failed.");
    e.line("Execute,");
    e.line("/// The response did not contain a usable result set.");
    e.line("Rows,");
    e.line("/// A row did not match the generated row type.");
    e.line("Deserialize,");
    e.close();
    e.blank();
    e.line("/// Error returned by every generated query function.");
    e.line("#[derive(Debug)]");
    e.open("pub struct CqlcError");
    e.line("/// Name of the query, as written in its `-- name:` annotation.");
    e.line("pub query: &'static str,");
    e.line("pub kind: CqlcErrorKind,");
    e.line("source: ::std::boxed::Box<dyn ::std::error::Error + Send + Sync + 'static>,");
    e.close();
    e.blank();
    e.open("impl CqlcError");
    e.open("fn new(query: &'static str, kind: CqlcErrorKind, source: impl ::std::error::Error + Send + Sync + 'static) -> Self");
    e.line("CqlcError { query, kind, source: ::std::boxed::Box::new(source) }");
    e.close();
    e.close();
    e.blank();
    e.open("impl ::std::fmt::Display for CqlcError");
    e.open("fn fmt(&self, f: &mut ::std::fmt::Formatter<'_>) -> ::std::fmt::Result");
    e.line("write!(f, \"query `{}` failed ({:?}): {}\", self.query, self.kind, self.source)");
    e.close();
    e.close();
    e.blank();
    e.open("impl ::std::error::Error for CqlcError");
    e.open("fn source(&self) -> Option<&(dyn ::std::error::Error + 'static)>");
    e.line("Some(&*self.source)");
    e.close();
    e.close();
    e.blank();
}

fn query(q: &Query, opts: &Options) -> Result<String, Vec<Diagnostic>> {
    let mut errors = Vec::new();
    let mut ty = |t: &CqlType, ord: bool| match rust_type(t, opts, ord) {
        Ok(s) => s,
        Err(msg) => {
            errors.push(Diagnostic::error(
                DiagnosticCode::UnsupportedType,
                q.span,
                msg,
            ));
            String::new()
        }
    };

    let snake = to_snake_case(&q.name);
    let pascal = to_pascal_case(&q.name);
    let cql_const = format!("{}_CQL", const_ident(&snake));
    let row = format!("{pascal}Row");
    let params_ty = format!("{pascal}Params");

    // Parameter and row field types.
    let params: Vec<(String, String, &Param)> = q
        .params
        .iter()
        .map(|p| {
            let t = ty(&p.cql_type, false);
            let t = if p.nullable {
                format!("::std::option::Option<{t}>")
            } else {
                t
            };
            (field_ident(&p.name), t, p)
        })
        .collect();
    let cols: Vec<(String, String, &str)> = q
        .columns
        .iter()
        .map(|c| {
            let t = ty(&c.cql_type, false);
            let t = if c.nullable {
                format!("::std::option::Option<{t}>")
            } else {
                t
            };
            (field_ident(&c.name), t, c.name.as_str())
        })
        .collect();
    for (what, names) in [
        (
            "parameter",
            params.iter().map(|p| p.0.as_str()).collect::<Vec<_>>(),
        ),
        ("result column", cols.iter().map(|c| c.0.as_str()).collect()),
    ] {
        if let Some(dup) = first_duplicate(&names) {
            errors.push(Diagnostic::error(
                DiagnosticCode::Duplicate,
                q.span,
                format!("{what} names clash after conversion to Rust: `{dup}`"),
            ));
        }
    }
    if !errors.is_empty() {
        return Err(errors);
    }

    let mut e = Emitter::default();
    let kind_name = match q.kind {
        QueryKind::One => ":one",
        QueryKind::Many => ":many",
        QueryKind::Exec => ":exec",
    };

    e.line(format!("/// CQL of [`{snake}`] (`{}`).", q.name));
    e.line(format!("pub const {cql_const}: &str = {:?};", q.cql));
    e.blank();

    if q.kind != QueryKind::Exec {
        e.line(format!("/// One result row of [`{snake}`]."));
        e.line("#[derive(Debug, Clone, PartialEq, ::scylla::DeserializeRow)]");
        e.open(format!("pub struct {row}"));
        for (field, t, cql_name) in &cols {
            if field != cql_name {
                e.line(format!("#[scylla(rename = {cql_name:?})]"));
            }
            e.line(format!("pub {field}: {t},"));
        }
        e.close();
        e.blank();
    }

    let use_struct = params.len() > 1;
    if use_struct {
        e.line(format!(
            "/// Bind values of [`{snake}`], in the order of the bind markers."
        ));
        e.line("#[derive(Debug, Clone, PartialEq)]");
        e.open(format!("pub struct {params_ty}"));
        for (field, t, p) in &params {
            e.line(format!("/// {}", param_doc(p)));
            e.line(format!("pub {field}: {t},"));
        }
        e.close();
        e.blank();
    }

    // Function signature.
    let ret = match q.kind {
        QueryKind::One => format!("::std::result::Result<::std::option::Option<{row}>, CqlcError>"),
        QueryKind::Many => format!("::std::result::Result<::std::vec::Vec<{row}>, CqlcError>"),
        QueryKind::Exec => "::std::result::Result<(), CqlcError>".to_string(),
    };
    let arg = match params.as_slice() {
        [] => String::new(),
        [(field, t, _)] => {
            let field = match field.as_str() {
                "session" | "prepared" | "result" | "rows" => format!("{field}_"),
                _ => field.clone(),
            };
            format!(", {field}: {t}")
        }
        _ => format!(", params: {params_ty}"),
    };
    let binding = match params.as_slice() {
        [] => "()".to_string(),
        [(field, _, _)] => {
            let field = match field.as_str() {
                "session" | "prepared" | "result" | "rows" => format!("{field}_"),
                _ => field.clone(),
            };
            format!("(&{field},)")
        }
        _ => format!(
            "({},)",
            params
                .iter()
                .map(|(f, _, _)| format!("&params.{f}"))
                .collect::<Vec<_>>()
                .join(", ")
        ),
    };

    e.line(format!("/// Runs query `{}` (`{kind_name}`).", q.name));
    e.line("///");
    e.line("/// ```text");
    e.line(format!("/// {}", q.cql));
    e.line("/// ```");
    match q.kind {
        QueryKind::One => {
            e.line("///");
            e.line(
                "/// Returns `None` if no row matched. The query is expected to match at most one",
            );
            e.line("/// row; if it matches several, the first one is returned.");
        }
        QueryKind::Many => {
            e.line("///");
            e.line("/// Loads the whole result set into memory (unpaged).");
        }
        QueryKind::Exec => {}
    }
    e.open(format!(
        "pub async fn {snake}(session: &::scylla::client::session::Session{arg}) -> {ret}"
    ));
    let name = format!("{:?}", q.name);
    e.open("let prepared = session.prepare(".to_string() + &cql_const + ").await.map_err(|e|");
    e.line(format!("CqlcError::new({name}, CqlcErrorKind::Prepare, e)"));
    e.close_with("})?;");
    let exec = format!("session.execute_unpaged(&prepared, {binding}).await");
    match q.kind {
        QueryKind::Exec => {
            e.line(format!(
                "{exec}.map_err(|e| CqlcError::new({name}, CqlcErrorKind::Execute, e))?;"
            ));
            e.line("Ok(())");
        }
        QueryKind::One | QueryKind::Many => {
            e.line(format!("let result = {exec}"));
            e.line(format!(
                "    .map_err(|e| CqlcError::new({name}, CqlcErrorKind::Execute, e))?;"
            ));
            e.line("let rows = result");
            e.line("    .into_rows_result()");
            e.line(format!(
                "    .map_err(|e| CqlcError::new({name}, CqlcErrorKind::Rows, e))?;"
            ));
            if q.kind == QueryKind::One {
                e.line(format!("rows.maybe_first_row::<{row}>()"));
                e.line(format!(
                    "    .map_err(|e| CqlcError::new({name}, CqlcErrorKind::Deserialize, e))"
                ));
            } else {
                e.line(format!("rows.rows::<{row}>()"));
                e.line(format!(
                    "    .map_err(|e| CqlcError::new({name}, CqlcErrorKind::Rows, e))?"
                ));
                e.line("    .collect::<::std::result::Result<::std::vec::Vec<_>, _>>()");
                e.line(format!(
                    "    .map_err(|e| CqlcError::new({name}, CqlcErrorKind::Deserialize, e))"
                ));
            }
        }
    }
    e.close();
    e.blank();
    Ok(e.finish().trim_end_matches('\n').to_string() + "\n")
}

fn param_doc(p: &Param) -> String {
    use cqlc_core::ir::ParamSource::*;
    let what = match &p.source {
        Restriction { column, op } => format!("`{column}` ({})", op.suffix()),
        Assignment { column } => format!("`{column}`"),
        Limit => "`LIMIT`".to_string(),
        Ttl => "`USING TTL` (seconds)".to_string(),
        Timestamp => "`USING TIMESTAMP` (microseconds)".to_string(),
    };
    if p.nullable {
        format!("{what}. `None` binds NULL (a delete marker), it does not leave the value unset.")
    } else {
        what
    }
}

fn first_duplicate<'a>(names: &[&'a str]) -> Option<&'a str> {
    let mut seen = std::collections::HashSet::new();
    names.iter().copied().find(|n| !seen.insert(*n))
}

fn check_name_clashes(ir: &Ir, errors: &mut Vec<Diagnostic>) {
    let mut fns: HashMap<String, &str> = HashMap::new();
    for q in &ir.queries {
        let snake = to_snake_case(&q.name);
        if let Some(prev) = fns.insert(snake.clone(), &q.name) {
            errors.push(
                Diagnostic::error(
                    DiagnosticCode::Duplicate,
                    q.span,
                    format!(
                        "queries `{prev}` and `{}` both map to the Rust name `{snake}`",
                        q.name
                    ),
                )
                .with_help("rename one of the queries"),
            );
        }
    }
}

/// Maps a CQL type to a Rust type path. `ord` demands a type with a total
/// order (set elements and map keys are stored in `BTreeSet`/`BTreeMap`).
pub fn rust_type(ty: &CqlType, opts: &Options, ord: bool) -> Result<String, String> {
    use CqlType::*;
    let chrono = opts.time_library == TimeLibrary::Chrono;
    if ord && !is_ord(ty) {
        return Err(format!(
            "`{ty}` cannot be a set element or map key: it has no total order in Rust"
        ));
    }
    Ok(match ty {
        Ascii | Text => "::std::string::String".into(),
        BigInt => "i64".into(),
        Blob => "::std::vec::Vec<u8>".into(),
        Boolean => "bool".into(),
        Counter => "::scylla::value::Counter".into(),
        Date if chrono => "::chrono::NaiveDate".into(),
        Date => "::scylla::value::CqlDate".into(),
        Decimal => "::scylla::value::CqlDecimal".into(),
        Double => "f64".into(),
        Duration => "::scylla::value::CqlDuration".into(),
        Float => "f32".into(),
        Inet => "::std::net::IpAddr".into(),
        Int => "i32".into(),
        SmallInt => "i16".into(),
        Time if chrono => "::chrono::NaiveTime".into(),
        Time => "::scylla::value::CqlTime".into(),
        Timestamp if chrono => "::chrono::DateTime<::chrono::Utc>".into(),
        Timestamp => "::scylla::value::CqlTimestamp".into(),
        TimeUuid => "::scylla::value::CqlTimeuuid".into(),
        TinyInt => "i8".into(),
        Uuid => "::uuid::Uuid".into(),
        VarInt => "::scylla::value::CqlVarint".into(),
        List(t) => format!("::std::vec::Vec<{}>", rust_type(t, opts, false)?),
        Set(t) => format!(
            "::std::collections::BTreeSet<{}>",
            rust_type(t, opts, true)?
        ),
        Map(k, v) => format!(
            "::std::collections::BTreeMap<{}, {}>",
            rust_type(k, opts, true)?,
            rust_type(v, opts, false)?
        ),
        Tuple(ts) => {
            let parts: Result<Vec<_>, _> = ts.iter().map(|t| rust_type(t, opts, false)).collect();
            format!("({},)", parts?.join(", "))
        }
        Frozen(t) => rust_type(t, opts, ord)?,
        Udt(name) => return Err(format!("user-defined type `{name}` is not supported yet")),
    })
}

fn is_ord(ty: &CqlType) -> bool {
    use CqlType::*;
    match ty {
        Ascii | Text | Boolean | TinyInt | SmallInt | Int | BigInt | Uuid | TimeUuid
        | Timestamp | Date | Time | Inet | Blob => true,
        List(t) | Set(t) | Frozen(t) => is_ord(t),
        Map(k, v) => is_ord(k) && is_ord(v),
        Tuple(ts) => ts.iter().all(is_ord),
        _ => false,
    }
}
