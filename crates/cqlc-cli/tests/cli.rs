use std::path::Path;
use std::process::{Command, Output};

fn cqlc(dir: &Path, args: &[&str]) -> Output {
    Command::new(env!("CARGO_BIN_EXE_cqlc"))
        .current_dir(dir)
        .args(args)
        .output()
        .unwrap()
}

fn project(schema: &str, queries: &str) -> tempfile::TempDir {
    let dir = tempfile::tempdir().unwrap();
    let p = dir.path();
    std::fs::create_dir_all(p.join("schema")).unwrap();
    std::fs::create_dir_all(p.join("queries")).unwrap();
    std::fs::write(p.join("schema/s.cql"), schema).unwrap();
    std::fs::write(p.join("queries/q.cql"), queries).unwrap();
    std::fs::write(
        p.join("cqlc.toml"),
        "schema = \"schema\"\nqueries = \"queries\"\n[rust]\nout = \"src/gen/queries.rs\"\n",
    )
    .unwrap();
    dir
}

const SCHEMA: &str = "CREATE TABLE t (k uuid PRIMARY KEY, v text);";
const QUERY: &str = "-- name: Get :one\nSELECT v FROM t WHERE k = ?;";

fn stderr(o: &Output) -> String {
    String::from_utf8_lossy(&o.stderr).into_owned()
}

#[test]
fn generate_then_check_roundtrip() {
    let dir = project(SCHEMA, QUERY);
    let out = dir.path().join("src/gen/queries.rs");

    // Nothing generated yet: --check fails and does not write.
    let o = cqlc(dir.path(), &["generate", "--check"]);
    assert_eq!(o.status.code(), Some(1));
    assert!(!out.exists());

    let o = cqlc(dir.path(), &["generate"]);
    assert!(o.status.success(), "{}", stderr(&o));
    let text = std::fs::read_to_string(&out).unwrap();
    assert!(text.starts_with("// @generated by cqlc"));
    assert!(text.contains("pub async fn get("));

    assert!(cqlc(dir.path(), &["generate", "--check"]).status.success());

    // Editing the query makes the committed output stale.
    std::fs::write(
        dir.path().join("queries/q.cql"),
        "-- name: Get :one\nSELECT k, v FROM t WHERE k = ?;",
    )
    .unwrap();
    let o = cqlc(dir.path(), &["generate", "--check"]);
    assert_eq!(o.status.code(), Some(1));
    assert!(stderr(&o).contains("out of date"));
    assert_eq!(
        std::fs::read_to_string(&out).unwrap(),
        text,
        "--check must not write"
    );
}

#[test]
fn errors_are_reported_with_code_and_location_and_nothing_is_written() {
    let dir = project(SCHEMA, "-- name: Get :one\nSELECT nope FROM t WHERE k = ?;");
    let o = cqlc(dir.path(), &["generate"]);
    assert_eq!(o.status.code(), Some(1));
    let err = stderr(&o);
    assert!(err.contains("error[CQL102]"), "{err}");
    assert!(err.contains("queries/q.cql:2:8"), "{err}");
    assert!(!dir.path().join("src/gen/queries.rs").exists());
}

#[test]
fn warnings_do_not_fail_unless_denied() {
    let dir = project(
        "CREATE TABLE t (a uuid, b int, v text, PRIMARY KEY ((a), b));",
        "-- name: Scan :many\nSELECT v FROM t WHERE b >= ?;",
    );
    let o = cqlc(dir.path(), &["check"]);
    assert!(o.status.success());
    assert!(stderr(&o).contains("warning[CQL201]"));
    let o = cqlc(dir.path(), &["check", "--deny-warnings"]);
    assert_eq!(o.status.code(), Some(1));
}

#[test]
fn missing_config_is_a_usage_error() {
    let dir = tempfile::tempdir().unwrap();
    let o = cqlc(dir.path(), &["check"]);
    assert_eq!(o.status.code(), Some(2));
    assert!(stderr(&o).contains("cqlc.toml"));
}
